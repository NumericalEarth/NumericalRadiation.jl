            "provenance_note" => "artifact generated from the working tree " *
                "before its own commit"),
        "disclaimer" => "script generation only; nothing submitted by this " *
                        "unit; LBL evaluation only; no optimizer, objective, " *
                        "floor, or recovery computation.",
    )
    mkpath(dirname(GA_RESULTS_JSON))
    open(GA_RESULTS_JSON, "w") do io
        JSON.print(io, result, 2)
    end
    open(GA_RESULTS_MD, "w") do io
        println(io, "# Gate-4 G2a SW-RGB training-flux checkpoint\n")
        println(io, "Status: **$status**\n")
        println(io, result["disclaimer"], "\n")
