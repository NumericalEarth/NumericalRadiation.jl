            "onto WN1_SW_RGB='250 14300 16650 20000 25000'; create_lut_sw " *
            "uses base_wavenumber_boundary=14300",
        "upstream_negative_probes" => [
            "404 ecpds/home/ckdmip/sw_fluxes-rgb/evaluation1/...",
            "404 ecpds/home/ckdmip/sw_fluxes/evaluation1/ckdmip_evaluation1_sw_fluxes-rgb_present.h5",
            "404 ecpds/home/ckdmip/evaluation1/sw_fluxes-rgb/...",
            "404 ecpds .../lw_fluxes/evaluation2/ckdmip_evaluation2_lw_fluxes_rel-415.h5",
            "404 ecpds .../sw_fluxes/evaluation2/ckdmip_evaluation2_sw_fluxes_rel-415.h5"],
        "scope" => scope_note,
        "expected_outputs" => ["$CKDMIP_ROOT/evaluation1/sw_fluxes-rgb/" *
            "ckdmip_evaluation1_sw_fluxes-rgb_rel-$lev.h5" for lev in CO2_LEVELS],
