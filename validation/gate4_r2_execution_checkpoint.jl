            structure_ok ? "passed" : "failed"
        structure_ok || push!(fails,
            "finding ledger structure invalid: output.sha256 " *
            (exp_out_wellformed ? "ok" : "missing/malformed/non-string") *
            "; attempts " *
            (isempty(attempts_obj) ? "missing/non-object" : "ok"))
