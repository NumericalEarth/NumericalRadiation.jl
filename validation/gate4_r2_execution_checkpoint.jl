            split(strip(read(`sha256sum $SW_RAW_V14`, String)))[1] == exp_out
        gates["v14_raw_output_matches_finding_ledger"] =
            out_ok ? "passed" : "failed"
        out_ok || push!(fails, "v1.4 raw output != finding-ledger sha " *
